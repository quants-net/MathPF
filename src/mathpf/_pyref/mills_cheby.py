def Rrel_below1(x):
    """Rrel_below1(x) = (sqrt(pi/2) - R(x))/x for x in [0,1] (12 segments,
    deg-7 each, >0); R(x) = M_SQRT2PI_2 - x*Rrel_below1(x).  Rrel_below1(0) = 1."""
    i = int(NSEG_RREL * x)
    if i >= NSEG_RREL:
        i = NSEG_RREL - 1
    s = NSEG_RREL * x - i
    o = i * 8
    c = C_Rrel
    return (((((((c[o+7])*s + c[o+6])*s + c[o+5])*s + c[o+4])*s + c[o+3])*s + c[o+2])*s + c[o+1])*s + c[o]


def R013_CF(x_or_u, n, d):
    """Shared CF convergent for R / -R' / -R''' at order n in {2,4,6,8,10,12}, d in {0,1,3}.

    Parameter ``x_or_u`` is interpreted polymorphically by ``d`` (u := x^2 + 3 is the
    natural shifted variable of the Mills CF):

        d = 0:  x_or_u = x          -> R^[n](x)       = N/(x D)         (Mills ratio)
        d = 1:  x_or_u = x*x + 3    -> -R'^[n](x)     = Delta/D         (R1^[n])
        d = 3:  x_or_u = x*x + 3    -> -R'''^[n](x)   = Gamma/D         (R3^[n]; n>=4)

    The d=1 / d=3 paths depend only on u, so accepting u directly skips both the
    ``x*x`` and the ``+ 3.0`` inside the kernel.  The d=1/d=3 callers (R1, R3
    dispatchers, R_DD's Taylor branch) need u anyway -- for the _U_MAX overflow
    guard (where u and x*x differ by 3, negligible at the saturation threshold)
    and for the descent denominator and ascent recurrence (which rewrites cleanly
    as (u+4), (u+8), (u+12) for r5/r7/r9).  The d=0 path keeps x because R^[n]
    has 1/x outside the polynomial.

    Uses the natural shift-3 variable u := x^2 + 3 (matches the Mills-ratio CF
    structure: -R''' = (x^2+3)(-R') - 1, etc.).  Evaluates the two smaller
    polynomials Delta(u) (deg n/2-1) and Gamma(u) (deg n/2-2), then recovers
        D = u * Delta - Gamma         (one mult, one sub)
        N = D - Delta                 (pure sub -- no mult, since N = (u-1)*Delta - Gamma
                                        = u*Delta - Gamma - Delta = D - Delta)
    Shifted coefficients are ~5x smaller in magnitude than the un-shifted form,
    and the recovery formulas are subtractions only; total cost is
    (n/2-1) + (n/2-2) Horner mults + 1 combine mult = (n-2) mults + 1 div.
    """
    if d == 0:
        u = x_or_u*x_or_u + 3.0                         # arg is x; form u inside
    else:
        u = x_or_u                                      # arg is already u = x^2 + 3
    if n == 2:                                          # Delta=1, Gamma=0 (degenerate); D = u, N = u-1
        if d == 0: return (u - 1.0) / (x_or_u * u)      # arg is x
        if d == 1: return 1.0 / u
        return 0.0                                      # -R'''^[2] vanishes
    # Gamma coefficients have the leading 6 baked in (saves one mult per call vs
    # the explicit `gamma = 6.0 * (...)` form, which is kept commented for reference).
    if n == 4:
        delta = 4.0 + u
        gamma = 6.0                                                                                                  # = 6.0
    elif n == 6:
        delta = 12.0 + u*(12.0 + u)
        gamma = 48.0 + u*6.0                                                                                          # = 6.0*(8.0 + u)
    elif n == 8:
        delta = -24.0 + u*(114.0 + u*(24.0 + u))
        gamma = 324.0 + u*(120.0 + u*6.0)                                                                             # = 6.0*(54.0 + u*(20.0 + u))
    elif n == 10:
        delta = -1248.0 + u*(936.0 + u*(426.0 + u*(40.0 + u)))
        gamma = 1728.0 + u*(1812.0 + u*(216.0 + u*6.0))                                                               # = 6.0*(288.0 + u*(302.0 + u*(36.0 + u)))
    elif n == 12:
        delta = -22320.0 + u*(4932.0 + u*(6816.0 + u*(1116.0 + u*(60.0 + u))))
        gamma = -1080.0 + u*(24768.0 + u*(5472.0 + u*(336.0 + u*6.0)))                                                # = 6.0*(-180.0 + u*(4128.0 + u*(912.0 + u*(56.0 + u))))
    else:
        raise ValueError(f"R013_CF: n={n} not supported (must be 2,4,6,8,10,12)")
    D = u*delta - gamma                                 # = (x^2+3)*Delta - Gamma
    if d == 1: return delta / D                         # -R'^[n] = Delta/D
    if d == 3: return gamma / D                         # -R'''^[n] = Gamma/D
    return (D - delta) / (x_or_u * D)                   # d == 0: R^[n] = N/(xD), N = D - Delta; arg is x


def R(x):
    """Mills ratio R(x) = N(-x)/n(x), scalar float (any sign)."""
    if x < 0.0:
        return M_SQRT2PI * math.exp(0.5 * x * x) - R(-x)
    if x <= 1.0:                        # R = sqrt(pi/2) - x*Rrel_below1(x)  (inlined segmented)
        i = int(NSEG_RREL * x)
        if i >= NSEG_RREL:
            i = NSEG_RREL - 1
        s = NSEG_RREL * x - i
        o = i * 8
        c = C_Rrel
        rrel = (((((((c[o+7])*s + c[o+6])*s + c[o+5])*s + c[o+4])*s + c[o+3])*s + c[o+2])*s + c[o+1])*s + c[o]
        return M_SQRT2PI_2 - x * rrel
    if x >= XCF_R[0]:                   # tiered CF convergents (shared with R1, R3 via R013_CF)
        if x >= XCF_R[6]: return 1.0 / x                          # x >= 67000000:        n=0 degenerate
        if x >= XCF_R[5]: return R013_CF(x, NCF_R[5], 0)          # x in [548, 67e6):     CF n=2
        if x >= XCF_R[4]: return R013_CF(x, NCF_R[4], 0)          # x in [59.3, 548):     CF n=4
        if x >= XCF_R[3]: return R013_CF(x, NCF_R[3], 0)          # x in [24.1, 59.3):    CF n=6
        if x >= XCF_R[2]: return R013_CF(x, NCF_R[2], 0)          # x in [15.1, 24.1):    CF n=8
        if x >= XCF_R[1]: return R013_CF(x, NCF_R[1], 0)          # x in [11.4, 15.1):    CF n=10
        return            R013_CF(x, NCF_R[0], 0)                 # x in [9.5, 11.4):     CF n=12 bridge
    d = N_FRAC_R1 + x                   # 1 < x < XCF_R[0]: R = (1 - R1)/x, R1 from C_R1
    i = int(NSEG_R1 * (x - 1.0) / d)
    if i >= TMAX_R1:
        i = TMAX_R1 - 1
    s = ((NSEG_R1 - i) * x - (NSEG_R1 + i * N_FRAC_R1)) / d
    o = i * 8
    c = C_R1
    return (1.0 - ((((((((c[o + 7])*s + c[o + 6])*s + c[o + 5])*s + c[o + 4])*s + c[o + 3])*s + c[o + 2])*s + c[o + 1])*s + c[o])) / x


def R1(x):
    """R1(x) = 1 - x R(x) = -R'(x), scalar float (any sign)."""
    if x < 0.0:                         # reflection: R1(x) = R1(-x) - M_SQRT2PI*x*exp(x^2/2)
        return M_SQRT2PI * (-x) * math.exp(0.5 * x * x) + R1(-x)
    if x <= 1.0:                        # R1 = 1 - x*R,  R = sqrt(pi/2)-x*Rrel_below1 (inlined segmented)
        i = int(NSEG_RREL * x)
        if i >= NSEG_RREL:
            i = NSEG_RREL - 1
        s = NSEG_RREL * x - i
        o = i * 8
        c = C_Rrel
        rrel = (((((((c[o+7])*s + c[o+6])*s + c[o+5])*s + c[o+4])*s + c[o+3])*s + c[o+2])*s + c[o+1])*s + c[o]
        return 1.0 - x * (M_SQRT2PI_2 - x * rrel)
    if x >= XCF_R1[0]:
        u = x*x + 3.0                                   # kernel's shifted variable; shared with _U_MAX guard and R013_CF
        if u > _U_MAX: return 0.0                       # +3 shift in threshold is invisible (_U_MAX >> 3 at saturation)
        if x >= XCF_R1[5]: return R013_CF(u, NCF_R1[5], 1)        # x >= 12800:           CF n=2
        if x >= XCF_R1[4]: return R013_CF(u, NCF_R1[4], 1)        # x in [165, 12800):    CF n=4
        if x >= XCF_R1[3]: return R013_CF(u, NCF_R1[3], 1)        # x in [41, 165):       CF n=6
        if x >= XCF_R1[2]: return R013_CF(u, NCF_R1[2], 1)        # x in [21.2, 41):      CF n=8
        if x >= XCF_R1[1]: return R013_CF(u, NCF_R1[1], 1)        # x in [14.5, 21.2):    CF n=10
        return            R013_CF(u, NCF_R1[0], 1)                # x in [11.5, 14.5):    CF n=12 bridge
    d = N_FRAC_R1 + x                   # 1 < x < XCF_R1[0]: deg-7 t-bucket
    i = int(NSEG_R1 * (x - 1.0) / d)
    if i >= TMAX_R1:
        i = TMAX_R1 - 1
    s = ((NSEG_R1 - i) * x - (NSEG_R1 + i * N_FRAC_R1)) / d
    o = i * 8
    c = C_R1
    return (((((((c[o + 7])*s + c[o + 6])*s + c[o + 5])*s + c[o + 4])*s + c[o + 3])*s + c[o + 2])*s + c[o + 1])*s + c[o]


